import type { InteractiveStep } from '../driver'
import { sleep, waitForElement } from '../driver'

export type CoachScheduleTourOptions = {
    returnPath: string
}

/**
 * Тур «Расписание» для тренера.
 *
 * Показывает:
 * - Легенда календаря
 * - «Изменить период» — bulk-изменение
 * - Клик по дню + «Редактировать N день»
 * - «Меня не будет» — быстрая отмена
 */
export function buildCoachScheduleTourSteps(
    options: CoachScheduleTourOptions
): InteractiveStep[] {
    const { returnPath } = options

    return [
        // ============ 1. Приветствие ============
        {
            kind: 'info',
            title: '📅 Расписание',
            description:
                'Научимся управлять расписанием тренировок. Тут ты меняешь статусы дней, отменяешь тренировки, отмечаешь турниры и праздники.',
        },

        // ============ 2. Переход в расписание ============
        {
            kind: 'navigate',
            to: '/schedule',
            waitFor: '[data-tour="schedule-calendar"]',
        },

        // ============ 3. Обзор календаря ============
        {
            kind: 'info',
            element: '[data-tour="schedule-calendar"]',
            title: '📆 Календарь',
            description:
                'Все тренировки клуба. <b>Точки под датами</b> — типы тренировок. Расшифровка цветов — снизу в <b>легенде</b>.',
            side: 'top',
            nextText: 'Далее →',
        },

        // ============ 4. Легенда ============
        {
            kind: 'info',
            element: '[data-tour="schedule-legend"]',
            title: '🎨 Легенда',
            description:
                'Что означает какой цвет:<br/>🟢 <b>Обычная</b> тренировка<br/>🟡 <b>Без тренера</b> (зал открыт для взрослых)<br/>🔵 <b>Замена</b><br/>🔴 <b>Отменена</b><br/>🟣 <b>Праздник</b><br/>🌸 <b>Турнир</b>',
            side: 'top',
            nextText: 'Далее →',
        },

        // ============ 5. Клик на «Изменить период» ============
        {
            kind: 'wait-click',
            element: '[data-tour="schedule-bulk-change"]',
            title: '📆 Изменить период',
            description:
                'Эта кнопка меняет статус <b>сразу нескольким дням</b>. Например, если ты в отпуске неделю — отметишь весь период отменённым за один раз. Тыкни, чтобы посмотреть.',
            side: 'bottom',
            waitForNext: '[role="dialog"]',
            waitTimeoutMs: 3000,
        },

        // ============ 6. Обзор диалога bulk change ============
        {
            kind: 'info',
            title: '🗓 Как работает',
            description:
                '1. <b>Выбираешь период</b> — тыкаешь на первую и последнюю дату в календаре<br/>2. <b>Указываешь причину</b> — отмена / без тренера / праздник и т.д.<br/>3. <b>Опционально</b>: своё сообщение для игроков<br/><br/>⚠️ <b>Важно:</b> изменение применится только к <b>тренировочным дням</b> (пн, вт, ср, чт, сб). Пятница и воскресенье пропускаются.',
            nextText: 'Понятно →',
        },

        // ============ 7. Закрой диалог ============
        {
            kind: 'wait-click',
            element: '[role="dialog"] button[type="button"]',
            title: '👇 Закрой диалог',
            description: 'Тыкни <b>«Отмена»</b>, чтобы закрыть окно. Дальше научимся редактировать один день.',
            side: 'top',
            waitTimeoutMs: 3000,
            onBefore: async () => {
                await sleep(300)
            },
        },

        // ============ 8. Клик на сегодняшний день ============
        {
            kind: 'wait-click',
            element: '[data-tour="schedule-day-today"]',
            title: '👆 Тыкни на сегодня',
            description:
                'Тыкни на <b>сегодняшний день</b> в календаре. Внизу появится кнопка "Редактировать N число".',
            side: 'top',
            waitForNext: '[data-tour="schedule-edit-day"]',
            waitTimeoutMs: 3000,
            onBefore: async () => {
                await waitForElement('[data-tour="schedule-day-today"]', 3000)
                await sleep(300)
            },
        },

        // ============ 9. Клик на «Редактировать день» ============
        {
            kind: 'wait-click',
            element: '[data-tour="schedule-edit-day"]',
            title: '✏️ Редактировать день',
            description:
                'Появилась кнопка. Тыкни на неё — откроется окно редактирования этого дня.',
            side: 'top',
            waitForNext: '[role="dialog"]',
            waitTimeoutMs: 3000,
        },

        // ============ 10. Обзор EditDayDialog ============
        {
            kind: 'info',
            title: '🎛 Что можно с одним днём',
            description:
                'Табы наверху:<br/>• <b>Обычная</b> — вернуть в норму<br/>• <b>Без тренера</b> — тебя не будет, но зал открыт<br/>• <b>Замена</b> — другой тренер, вписываешь имя<br/>• <b>Отменена</b> — тренировки не будет<br/>• <b>Праздник</b> — выходной<br/>• <b>Турнир</b> — соревнования, можно указать время начала<br/>• <b>Изменить время</b> — сдвинуть время старта на этот день',
            nextText: 'Далее →',
        },

        // ============ 11. Инфо про автопосты ============
        {
            kind: 'info',
            title: '📢 Автоматические уведомления',
            description:
                'Как только ты сохраняешь изменение — <b>в ленте автоматически появляется пост</b>, а на главной у всех игроков — плашка с новостью. Никого предупреждать вручную не нужно.<br/><br/>Через день после этого дня — пост автоматически удаляется из ленты, чтобы не засорять.',
            nextText: 'Понятно →',
        },

        // ============ 12. Закрой диалог ============
        {
            kind: 'wait-click',
            element: '[role="dialog"] button[type="button"]',
            title: '👇 Закрой окно',
            description: 'Тыкни <b>«Отмена»</b>, чтобы закрыть.',
            side: 'top',
            waitTimeoutMs: 3000,
            onBefore: async () => {
                await sleep(300)
            },
        },

        // ============ 13. Инфо про «Меня не будет» ============
        {
            kind: 'info',
            element: '[data-tour="schedule-quick-cancel"]',
            title: '❌ «Меня не будет»',
            description:
                'Быстрая кнопка: <b>одним кликом отменить ближайшую тренировку</b>. Полезно если ты внезапно не сможешь прийти. В ленте автоматически появится объявление.',
            side: 'bottom',
            nextText: 'Понятно →',
        },

        // ============ 14. Финиш ============
        {
            kind: 'navigate',
            to: returnPath,
        },
        {
            kind: 'info',
            title: '🎉 Готово!',
            description:
                'Теперь ты знаешь как управлять расписанием. Все изменения сразу видны игрокам через автопосты и уведомления на главной.',
            nextText: 'Закрыть ✓',
        },
    ]
}
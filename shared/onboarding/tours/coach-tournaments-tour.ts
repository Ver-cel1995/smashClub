import type { InteractiveStep } from '../driver'
import { sleep } from '../driver'

export type CoachTournamentsTourOptions = {
    returnPath: string
}

/**
 * Тур «Турниры и AI» для тренера. Самый подробный.
 *
 * Показывает:
 * - Список турниров
 * - Клик на "+ Новый"
 * - PDF Dropzone (объяснение как работает AI)
 * - Пример распознанных данных (СКРИНШОТ!)
 * - Клик «Заполнить вручную»
 * - Обзор формы
 * - Клик «Отмена»
 * - Инфо про календарь
 */
export function buildCoachTournamentsTourSteps(
    options: CoachTournamentsTourOptions
): InteractiveStep[] {
    const { returnPath } = options

    return [
        // ============ 1. Приветствие ============
        {
            kind: 'info',
            title: '🏆 Турниры и AI-магия',
            description:
                'Самый интересный раздел! Тут ты создаёшь <b>анонсы турниров</b>. Главная фишка — можно <b>загрузить PDF-положение</b>, а AI автоматически заполнит все поля. Тебе останется только проверить и опубликовать.',
        },

        // ============ 2. Переход в турниры ============
        {
            kind: 'navigate',
            to: '/tournaments',
            waitFor: 'main',
        },

        // ============ 3. Обзор списка ============
        {
            kind: 'info',
            title: '📋 Список турниров',
            description:
                'Здесь <b>все активные турниры</b>: домашние (🏠) и выездные (🚗). Ближайшие сверху. <b>Прошедшие турниры автоматически удаляются</b> из списка (и из базы) — архива нет, всё чисто.',
            nextText: 'Далее →',
        },

        // ============ 4. Клик на "+ Новый" ============
        {
            kind: 'wait-click',
            element: '[data-tour="tournaments-create"]',
            title: '➕ Создать турнир',
            description:
                'Кнопка <b>«+ Новый»</b> справа сверху. Тыкни, чтобы начать создание.',
            side: 'bottom',
            waitForNext: 'main',
            waitTimeoutMs: 5000,
        },

        // ============ 5. Про PDF Dropzone ============
        {
            kind: 'info',
            title: '📄 Загрузка PDF — магия начинается',
            description:
                'На этом экране два варианта:<br/>• <b>Загрузить PDF</b> — AI прочитает положение и заполнит форму за 5-10 секунд<br/>• <b>Заполнить вручную</b> — если PDF нет или хочешь ввести всё сама<br/><br/>Обычно у нас положения приходят в мессенджере файлом. Скачиваешь его на телефон, потом тут — <b>перетаскиваешь</b> или тыкаешь и выбираешь.',
            nextText: 'Далее →',
        },

        // ============ 6. Пример распознавания (скриншот) ============
        {
            kind: 'info',
            title: '🎯 Что AI распознаёт',
            description: `
                <p style="margin: 0 0 8px 0">Вот пример: <b>официальное положение</b> с турнира в ст. Голубицкой. AI автоматически извлёк:</p>
                <div style="margin-top: 12px; text-align: center">
                    <img src="/onboarding/ai-parsing-example.png"
                         alt="Пример распознавания AI"
                         style="max-width: 100%; max-height: 340px; border-radius: 12px; border: 1px solid var(--border-card)"
                         onerror="this.style.display='none'; this.nextElementSibling.style.display='block'" />
                    <p style="display: none; padding: 20px; background: var(--bg-subtle); border-radius: 12px; color: var(--text-muted); font-size: 12px; text-align: left">
                        <b>Пример распознавания:</b><br/>
                        • Название: «Всероссийские соревнования "Кубок двух морей"»<br/>
                        • Тип: Выездной<br/>
                        • Организатор: Национальная федерация бадминтона<br/>
                        • Город: ст. Голубицкая<br/>
                        • Зал: СК «Олимп»<br/>
                        • Адрес: ул. Курортная, 106<br/>
                        • Даты: 20.09 – 25.09<br/>
                        • Дедлайн регистрации: 15.09<br/>
                        • Взнос: 2000 ₽ + пояснение<br/>
                        • Награды: медали, дипломы, призы<br/>
                        • Категории: 5 категорий (МО/ЖО/МП/ЖП/СмП) для 2011 г.р.
                    </p>
                </div>
            `,
            nextText: 'Впечатляет →',
        },

        // ============ 7. Клик «Заполнить вручную» (реальный AI не запускаем) ============
        {
            kind: 'info',
            title: '👉 Что дальше',
            description:
                'Сейчас посмотрим форму. Не будем реально загружать PDF (это уже проверял), а откроем <b>ручной ввод</b> — там ты увидишь <b>все поля формы</b>, которые AI заполняет автоматически.',
            nextText: 'Показать форму →',
        },
        {
            kind: 'wait-click',
            element: '[data-tour="tournaments-manual-fill"]',
            title: '👆 Тыкни «Заполнить вручную»',
            description: 'Внизу экрана есть кнопка <b>«Заполнить вручную»</b>. Тыкни по ней.',
            side: 'top',
            waitForNext: 'form',
            waitTimeoutMs: 5000,
        },

        // ============ 8. Обзор формы (первая часть) ============
        {
            kind: 'info',
            title: '📝 Форма турнира — часть 1',
            description:
                'Начало формы:<br/>• <b>Название</b> — обязательное<br/>• <b>Тип соревнования</b> — 🏠 Домашний (у нас в зале) или 🚗 Выездной<br/>• <b>Организатор</b> — кто проводит<br/>• <b>Место</b> — город, зал, адрес<br/>• <b>Даты</b> — начало, окончание, дедлайн регистрации',
            nextText: 'Далее →',
        },

        // ============ 9. Прокрутить вниз, обзор ============
        {
            kind: 'info',
            title: '📝 Форма — часть 2',
            description:
                'Ниже:<br/>• <b>Расписание дня</b> — время мандатной комиссии и начала игр<br/>• <b>Награды</b> — что получают призёры (медали, кубки, дипломы)<br/>• <b>Взнос</b> — сумма в рублях + пояснение если нужно<br/>• <b>Категории</b> — обязательно! Каждая категория = «разряд + возраст»<br/>• <b>Описание</b> — условия допуска<br/>• <b>Контакты</b> — телефон организатора',
            nextText: 'Далее →',
            onBefore: async () => {
                window.scrollTo({ top: window.innerHeight * 1.5, behavior: 'smooth' })
                await sleep(500)
            },
        },

        // ============ 10. Инфо про домашние турниры и календарь ============
        {
            kind: 'info',
            title: '📅 Магия для домашних турниров',
            description:
                'Если ты выбрала тип <b>🏠 Домашний</b> — этот турнир <b>автоматически появится в календаре расписания</b> на все даты турнира. Розовая точка на календаре, клик — и попадаешь на страницу турнира. Ничего дублировать не нужно.',
            nextText: 'Понятно →',
        },

        // ============ 11. Финиш ============
        {
            kind: 'navigate',
            to: returnPath,
        },
        {
            kind: 'info',
            title: '🎉 Готово!',
            description:
                'Теперь ты знаешь всю магию создания турниров. AI сделает большую часть работы, тебе останется только <b>проверить и опубликовать</b>. Экскурсию можно повторить в любой момент в <b>Настройки → Помощь</b>.',
            nextText: 'Закрыть ✓',
        },
    ]
}